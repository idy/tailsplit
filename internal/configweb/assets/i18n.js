  const reverse = new Map(Object.entries(en).filter(([, value]) => typeof value === 'string').map(([key, value]) => [value, key]));
  const preferred = (navigator.languages || [navigator.language || 'en'])[0] || 'en';
  let language = /^zh(?:[-_]|$)/i.test(preferred) ? 'zh' : 'en';
  const subscribers = new Set();
  const bindings = [];

  function t(key, values = {}) {
    const canonical = Object.hasOwn(en, key) || Object.hasOwn(zh, key) ? key : reverse.get(key) || key;
    let text = language === 'en' ? en[canonical] ?? canonical : zh[canonical] ?? canonical;
    if (typeof text === 'object') text = text[new Intl.PluralRules(language).select(values.count)] || text.other;
    return String(text).replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
  }

  function capture() {
    // Bind text nodes, not innerHTML: icons, control state and user drafts remain intact.
    if (!document.createTreeWalker) return;
    const walker = document.createTreeWalker(document.body, 4);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const key = node.nodeValue.trim();
      if (!Object.hasOwn(en, key) || node.parentElement.closest('script, style, pre, code, textarea')) continue;
      const before = node.nodeValue.match(/^\s*/)[0], after = node.nodeValue.match(/\s*$/)[0];
      bindings.push(() => { if (node.isConnected) node.nodeValue = before + t(key) + after; });
    }
    for (const node of document.querySelectorAll('[placeholder], [title], [aria-label]')) {
      for (const attribute of ['placeholder', 'title', 'aria-label']) {
        const key = node.getAttribute(attribute);
        if (Object.hasOwn(en, key)) bindings.push(() => node.setAttribute(attribute, t(key)));
      }
    }
  }
